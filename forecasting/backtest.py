"""Rolling-origin backtest: LightGBM quantile vs seasonal naive.

8 folds, origins 4 weeks apart, each fold scores horizons 1-4 and is trained
only on rows whose target week is at or before its origin (no leakage).

Reports WAPE (headline), WAPE on the subset where a seasonal-naive value
exists, and empirical coverage of the nominal 80% interval, overall and by
horizon. Writes evaluation/results/forecast_backtest.{md,json,png}.

    python -m forecasting.backtest
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from app.db.session import rw_engine
from forecasting.features import FEATURES, dense_panel, last_complete_week, load_weekly, training_frame
from forecasting.train import fit_quantiles, top_skus

N_FOLDS = 8
STEP_WEEKS = 4
EVAL_HORIZONS = range(1, 5)
RESULTS = Path(__file__).resolve().parents[1] / "evaluation" / "results"


def wape(y: np.ndarray, yhat: np.ndarray) -> float:
    return float(np.abs(y - yhat).sum() / max(np.abs(y).sum(), 1e-9))


def main() -> None:
    engine = rw_engine()
    last_week = last_complete_week(engine)
    panel = dense_panel(load_weekly(engine, top_skus()), last_week)
    frame = training_frame(panel)

    preds = []
    for k in range(N_FOLDS, 0, -1):
        origin = last_week - pd.Timedelta(weeks=STEP_WEEKS * k)
        train = frame[frame["target_week"] <= origin]
        test = frame[(frame["origin"] == origin) & frame["h"].isin(EVAL_HORIZONS)].copy()
        models = fit_quantiles(train)
        q = np.sort(np.column_stack([models[a].predict(test[FEATURES]) for a in (0.1, 0.5, 0.9)]), axis=1)
        q = np.clip(q, 0, None) * test["scale"].to_numpy()[:, None]
        test["p10"], test["p50"], test["p90"] = q[:, 0], q[:, 1], q[:, 2]
        test["snaive"] = test["seasonal_naive_raw"].fillna(test["last_value_raw"])
        test["ma4"] = test["roll_mean_4"] * test["scale"]
        test["fold"] = N_FOLDS - k + 1
        preds.append(test)
        print(f"fold {N_FOLDS - k + 1}: origin {origin:%Y-%m-%d} train_rows={len(train):,} "
              f"WAPE model={wape(test.y.values, test.p50.values):.3f} snaive={wape(test.y.values, test.snaive.values):.3f}")

    p = pd.concat(preds, ignore_index=True)
    inside = (p["y"] >= p["p10"]) & (p["y"] <= p["p90"])
    has_sn = p["seasonal_naive_raw"].notna()
    summary = {
        "n_skus": int(p["stock_code"].nunique()),
        "n_predictions": int(len(p)),
        "folds": N_FOLDS,
        "horizons": list(EVAL_HORIZONS),
        "wape_model": wape(p.y.values, p.p50.values),
        "wape_seasonal_naive": wape(p.y.values, p.snaive.values),
        "wape_moving_average_4": wape(p.y.values, p.ma4.values),
        "wape_model_where_seasonal_available": wape(p.y[has_sn].values, p.p50[has_sn].values),
        "wape_seasonal_naive_where_available": wape(p.y[has_sn].values, p.snaive[has_sn].values),
        "interval_coverage_80": float(inside.mean()),
        "coverage_by_horizon": {int(h): float(inside[p.h == h].mean()) for h in EVAL_HORIZONS},
        "wape_by_fold": {
            int(f): {"model": wape(g.y.values, g.p50.values), "seasonal_naive": wape(g.y.values, g.snaive.values),
                     "coverage": float(((g.y >= g.p10) & (g.y <= g.p90)).mean()),
                     "origin": f"{g.origin.iloc[0]:%Y-%m-%d}"}
            for f, g in p.groupby("fold")
        },
    }
    summary["wape_improvement_pct"] = 100 * (1 - summary["wape_model"] / summary["wape_seasonal_naive"])

    RESULTS.mkdir(parents=True, exist_ok=True)
    (RESULTS / "forecast_backtest.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    write_markdown(summary)
    plot(p, summary)
    print(json.dumps({k: v for k, v in summary.items() if not isinstance(v, dict)}, indent=2))


def write_markdown(s: dict) -> None:
    lines = [
        "# Forecast backtest",
        "",
        f"Rolling origin, {s['folds']} folds x horizons 1-4 weeks, top {s['n_skus']} SKUs by volume, "
        f"{s['n_predictions']:,} SKU-week predictions. Generated by `python -m forecasting.backtest`.",
        "",
        "| Metric | LightGBM quantile | Seasonal naive | 4-week moving average |",
        "|---|---:|---:|---:|",
        f"| WAPE (all) | {s['wape_model']:.1%} | {s['wape_seasonal_naive']:.1%} | {s['wape_moving_average_4']:.1%} |",
        f"| WAPE (where last-year value exists) | {s['wape_model_where_seasonal_available']:.1%} "
        f"| {s['wape_seasonal_naive_where_available']:.1%} | - |",
        f"| 80% interval coverage | {s['interval_coverage_80']:.1%} | - | - |",
        "",
        f"WAPE improvement over seasonal naive: **{s['wape_improvement_pct']:.1f}%**. "
        "Seasonal naive falls back to the last observed week when a SKU has no sales history "
        "from 52 weeks earlier.",
        "",
        "| Fold | Origin | WAPE model | WAPE s-naive | Coverage |",
        "|---:|---|---:|---:|---:|",
        *[f"| {f} | {v['origin']} | {v['model']:.1%} | {v['seasonal_naive']:.1%} | {v['coverage']:.1%} |"
          for f, v in s["wape_by_fold"].items()],
        "",
        "Coverage by horizon: " + ", ".join(f"h={h}: {c:.1%}" for h, c in s["coverage_by_horizon"].items()),
        "",
        "![coverage](forecast_coverage.png)",
    ]
    (RESULTS / "forecast_backtest.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def plot(p: pd.DataFrame, s: dict) -> None:
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, axes = plt.subplots(1, 2, figsize=(11, 4))
    folds = sorted(s["wape_by_fold"])
    cov = [s["wape_by_fold"][f]["coverage"] for f in folds]
    axes[0].bar([str(f) for f in folds], cov, color="#4C72B0")
    axes[0].axhline(0.8, color="#C44E52", linestyle="--", label="nominal 80%")
    axes[0].set_ylim(0, 1)
    axes[0].set_xlabel("fold")
    axes[0].set_ylabel("empirical coverage")
    axes[0].set_title("80% interval coverage by fold")
    axes[0].legend()

    top = p.groupby("stock_code")["y"].sum().idxmax()
    g = p[(p.stock_code == top)].sort_values("target_week")
    axes[1].fill_between(g.target_week, g.p10, g.p90, alpha=0.3, label="80% interval")
    axes[1].plot(g.target_week, g.p50, label="p50")
    axes[1].plot(g.target_week, g.y, "k.", label="actual")
    axes[1].set_title(f"Backtest predictions, SKU {top}")
    axes[1].tick_params(axis="x", rotation=45)
    axes[1].legend()
    fig.tight_layout()
    fig.savefig(RESULTS / "forecast_coverage.png", dpi=120)


if __name__ == "__main__":
    main()
