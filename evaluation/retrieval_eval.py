"""Retrieval-only evaluation on the 15 policy tasks (no LLM needed).

Compares dense top-5 against dense top-20 -> cross-encoder -> top-5, using the
raw task question as the query. The agent writes its own search queries, so
its in-loop Recall@5 (reported by run_eval) can differ from this number.

    python -m evaluation.retrieval_eval
"""
from __future__ import annotations

import json

from evaluation.metrics import load_tasks, recall_at_5
from evaluation.run_eval import RESULTS
from retrieval.store import search


def main() -> None:
    tasks = load_tasks(["policy"])
    rows = []
    for t in tasks:
        expected = t.spec["expected_sections"]
        dense = [h.citation.strip("[]") for h in search(t.question, k=5, use_rerank=False)]
        rr = [h.citation.strip("[]") for h in search(t.question, k=5, use_rerank=True)]
        rows.append({"task_id": t.id, "expected": expected, "dense_top5": dense, "rerank_top5": rr,
                     "recall_dense": recall_at_5(expected, dense), "recall_rerank": recall_at_5(expected, rr),
                     "hit1_dense": any(e.replace(" ", "") == dense[0].replace(" ", "") for e in expected),
                     "hit1_rerank": any(e.replace(" ", "") == rr[0].replace(" ", "") for e in expected)})
    n = len(rows)
    summary = {
        "n_queries": n,
        "recall_at_5_dense": sum(r["recall_dense"] for r in rows) / n,
        "recall_at_5_rerank": sum(r["recall_rerank"] for r in rows) / n,
        "hit_at_1_dense": sum(r["hit1_dense"] for r in rows) / n,
        "hit_at_1_rerank": sum(r["hit1_rerank"] for r in rows) / n,
    }
    (RESULTS / "retrieval_eval.json").write_text(json.dumps({"summary": summary, "rows": rows}, indent=2,
                                                            ensure_ascii=False), encoding="utf-8")
    lines = [
        "# Retrieval evaluation (policy tasks)", "",
        f"{n} queries (the raw policy-task questions), 65 chunks, BGE-small + ms-marco MiniLM cross-encoder. "
        "Generated by `python -m evaluation.retrieval_eval`.", "",
        "| Retriever | Recall@5 | Hit@1 |", "|---|---:|---:|",
        f"| Dense top-5 | {summary['recall_at_5_dense']:.1%} | {summary['hit_at_1_dense']:.1%} |",
        f"| Dense top-20 -> rerank top-5 | {summary['recall_at_5_rerank']:.1%} | {summary['hit_at_1_rerank']:.1%} |",
        "", "| Task | Expected | Rerank top-5 | Recall |", "|---|---|---|---:|",
        *[f"| {r['task_id']} | {', '.join(r['expected'])} | {', '.join(r['rerank_top5'])} | {r['recall_rerank']:.2f} |"
          for r in rows],
    ]
    (RESULTS / "retrieval_eval.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
